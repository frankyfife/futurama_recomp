"""Reproduces the single-point checks of the renderer.md review (section Verifikation).
Each block prints the raw evidence (disassembly / data / callgraph) for one claim."""
import re, struct
from verify_renderer_common import *
def hdr(t): print("\n=== " + t)
def calls(a): return sorted(f"{c:#x} {F.get(c, ('?',))[0]}" for c in callers(a))
hdr("K1 Create call site 0xd26be-0xd26e7 (push order = reversed args; add esp,0x20 = cdecl)")
for i in dis(0xd26be, 0x2c): print(fmt(i))
print("callers 0x14c170:", calls(0x14c170), " callers ctor 0x14af00:", calls(0x14af00))
hdr("K2 app vtable 0x2a3ef8 slots 0-8, slot5 body, slot-5 call count in decomp")
print([hex(X.u32(0x2a3ef8 + 4 * i)) for i in range(9)])
for i in dis(0xd2690, 7): print(fmt(i))
D = alldecomp()
n = sum(len(re.findall(r"\(\*\*\(code \*\*\)\(\*(?:\(int \*\))?DAT_002(?:eb310|e7b84) \+ 0x14\)\)", t)) for t in D.values())
print("(*DAT_002eb310/DAT_002e7b84 + 0x14)() occurrences:", n)
hdr("K9 vf16 / vf17 bodies")
for a, nb in ((0x146460, 0x29), (0x146551, 0xa5)):
    for i in dis(a, nb): print(fmt(i))
hdr("Create constants: push buffer size, frustum/port, clear defaults")
print("PushBufferSize args", hex(X.u32(0x2d7cec)), hex(X.u32(0x2d7cf0)))
print([l.strip() for l in decomp(0x147cd0).split("\n") if re.search(r"\+ 0x2(cc|d0|d4)\) =", l)])
hdr("Slot 31/42/59 stack args")
for i in dis(0x146990, 0xb): print(fmt(i))
print("TextureManager vtable 0x2abd90 slot3 =", hex(X.u32(0x2abd90 + 0xc)), [fmt(i) for i in dis(0x15f7e0, 0xb0) if i.mnemonic == "ret"])
print("vf42 rets:", [fmt(i) for i in dis(0x14b700, 0x520) if i.mnemonic == "ret"])
print("vf59 chain:", [fmt(i) for i in dis(0x146e90, 0xb)], [fmt(i) for i in dis(0x158ba0, 0xb)], [fmt(i) for i in dis(0x1618a0, 0x38) if i.mnemonic == "ret"])
hdr("Fixed pixel shader: SetPixelShader users in .text decomp")
for a, t in sorted(D.items()):
    if 0x11000 <= a < 0x2342c0 and "PixelShader" in t:
        print(hex(a), [l.strip() for l in t.split("\n") if "PixelShader" in l])
hdr("Texture upload: swizzle condition in FUN_0015db00, bpp table, pixel-format masks")
print([l.strip() for l in decomp(0x15db00).split("\n") if "cVar1 == '\0'" in l or "uVar3 < 8" in l])
print("FUN_00158790(0xb/0xc/0xe/0xf) cases:", [l.strip() for l in decomp(0x158790).split("\n") if "case 0xb" in l or "case 0xc:" in l])
print("mask/shift 0x2d7b6c/0x2d7b7c:", hex(X.u32(0x2d7b6c)), hex(X.u32(0x2d7b7c)))
hdr("NiScreenPolygon: ctor vtable store, callers of ctor / AddScreenPolygon / RemoveScreenPolygon")
for i in dis(0x106d77, 7): print(fmt(i))
print("ctor 0x106d50 callers:", calls(0x106d50))
for i in dis(0x19489, 0x18): print(fmt(i))
print("0x19460 callers:", calls(0x19460))
print("0x100f30 callers:", calls(0x100f30))
hdr("Movie player pokes NiXBoxSourceTextureData / renderer+0x5cc")
print("\n".join(l.strip() for l in decomp(0xee220).split("\n") if re.search(r"iVar6 \+ 0x(3c|48|4c|54|58|60)\)|0x5cc|FUN_00118600|CreateTexture2", l)))
hdr("Texture preload flag DAT_002d7900 and NiSourceTexture::Create(pixeldata) callers")
print("DAT_002d7900 =", X.read(0x2d7900, 1).hex(), " FUN_00118600 callers:", calls(0x118600), " FUN_00110d40 callers:", calls(0x110d40))
hdr("PrecacheGeometry CPU-data release in FUN_00148300 and game call args")
print("\n".join(l.strip() for l in decomp(0x148300).split("\n") if re.search(r"FUN_001437e0|FUN_00115db0|FUN_0011bc00|0x100U|0xfffe", l)))
for a in (0xce930, 0xd0dd0, 0xd1120):
    print(hex(a), [l.strip() for l in D[a].split("\n") if "+ 0x9c))" in l])
hdr("Main loop clear mode DAT_002d6740 initial value")
print(hex(X.u32(0x2d6740)))
hdr("Primitive table 0x293998")
print([struct.unpack_from("<II", X.read(0x293998, 88), 8 * i) for i in range(11)])
hdr("SetRenderTarget -> screen offset helpers")
print("0xa1920 callers:", calls(0xa1920), " 0xa1930 callers:", calls(0xa1930))
